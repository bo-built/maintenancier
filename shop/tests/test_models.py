from datetime import timedelta
from django.utils import timezone
from shop.models import (
    MaintenanceScheduleItem,
    MaintenanceLogEntry,
)
from shop.test_utils import PopulatedTestBase


class TestMaintenanceItems(PopulatedTestBase):

    def test_first_log_item_autogenerated_start_specified(self):
        '''
            When a new Maintenance Schedule Item is created, there should
            be a new Maintenance Log Item created with a due date that is
            x number of days from the Schedule item's start date, where x
            is the interval set for Maintenance Log Item.

            When start date is specified, the due date should be be
            start_date + x
        '''
        interval = 14
        today = timezone.localdate()
        start_date = today + timedelta(days=7)
        new_maintenance_item = MaintenanceScheduleItem.objects.create(
            shop=self.shop,
            machine=self.machines[0],
            interval=interval,
            name='New maintenance item',
            start_date=start_date,
        )

        expected_log_item = MaintenanceLogEntry.objects.filter(item=new_maintenance_item).first()
        self.assertIsNotNone(expected_log_item)
        self.assertEqual(expected_log_item.due_date, start_date)

    def test_log_item_status_save(self):
        log_item = self.log_items[3]
        log_item.status = 'done'
        log_item.save()
        log_item.refresh_from_db()
        self.assertEqual(log_item._description, log_item.item.description)
        self.assertEqual(log_item._item_name, log_item.item.name)
        self.assertEqual(log_item._machine_name, log_item.item.machine.name)